#!/usr/bin/env python3
"""Derive MANIFEST.in from pyproject package-data and sdist-only declarations.

Run from the checkout: python tools/build/generate_manifest.py [--check].
All distributions retain standalone setuptools builds; none imports another
distribution or the runtime to enumerate resources.
"""

import argparse
import fnmatch
from pathlib import Path
import sys

try:
    import tomllib
except ImportError:
    try:
        import tomli as tomllib
    except ImportError:
        from setuptools._vendor import tomli as tomllib


ROOT = Path(__file__).resolve().parents[2]
IGNORED_DIRECTORIES = frozenset({
    "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache", ".git", ".nox",
    ".ipynb_checkpoints", ".doctrees", "_build",
})
IGNORED_SUFFIXES = frozenset({".pyc", ".pyo", ".pyd", ".ipynb", ".mo"})


def config_at(project):
    with (project / "pyproject.toml").open("rb") as stream:
        return tomllib.load(stream)


def package_directory(package, mappings):
    """Apply setuptools' longest matching package-dir prefix."""
    parts = package.split(".")
    for count in range(len(parts), 0, -1):
        prefix = ".".join(parts[:count])
        if prefix in mappings:
            return Path(mappings[prefix]).joinpath(*parts[count:])
    return Path(mappings.get("", "")).joinpath(*parts)


def clean_file(path, project, excluded):
    relative = path.relative_to(project)
    if not path.is_file() or any(part in IGNORED_DIRECTORIES for part in relative.parts):
        return False
    if path.suffix in IGNORED_SUFFIXES or path.name == ".DS_Store":
        return False
    return not any(fnmatch.fnmatchcase(relative.as_posix(), pattern) for pattern in excluded)


def runtime_resources(project, config=None):
    """Return source -> wheel-member mappings from the sole resource table."""
    config = config or config_at(project)
    settings = config["tool"]["setuptools"]
    excluded = config.get("tool", {}).get("jittor", {}).get("sdist", {}).get("exclude", [])
    result = {}
    for package, patterns in settings.get("package-data", {}).items():
        if "*" in package:
            raise ValueError("resource owners must name an explicit package")
        directory = project / package_directory(package, settings.get("package-dir", {}))
        for pattern in patterns:
            for path in directory.glob(pattern):
                if clean_file(path, project, excluded):
                    member = (Path(*package.split(".")) / path.relative_to(directory)).as_posix()
                    result[path.relative_to(project).as_posix()] = member
    return dict(sorted(result.items()))


def manifest_text(project):
    project = Path(project)
    config = config_at(project)
    selections = config.get("tool", {}).get("jittor", {}).get("sdist", {})
    files = set(runtime_resources(project, config))
    files.update({"pyproject.toml", "MANIFEST.in"})
    if (project / "setup.py").is_file():
        files.add("setup.py")
    for pattern in selections.get("include", []):
        # A directory selection is recursive. Resource glob semantics remain
        # ordinary pathlib globs, matching setuptools package-data ownership.
        if pattern.endswith("/**"):
            candidates = (project / pattern[:-3]).rglob("*")
        else:
            candidates = project.glob(pattern)
        for path in candidates:
            if clean_file(path, project, selections.get("exclude", [])):
                files.add(path.relative_to(project).as_posix())
    lines = [
        "# Generated by tools/build/generate_manifest.py; do not edit.",
        "# Source: pyproject.toml [tool.setuptools.package-data] and [tool.jittor.sdist].",
        "# Exact paths avoid MANIFEST glob's non-recursive ** and cache leakage.",
    ]
    # MANIFEST's parser splits on whitespace and has no quoting syntax.
    # The repository's spaced notebook names live in explicitly selected
    # source-only trees; a one-character glob keeps each full path anchored.
    lines.extend("include " + "".join("?" if char.isspace() else char for char in name)
                 for name in sorted(files))
    lines.extend("prune " + pattern[:-3] for pattern in selections.get("exclude", [])
                 if pattern.endswith("/**"))
    lines.append("global-exclude *.py[cod] *.ipynb *.mo .DS_Store")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--project", action="append", type=Path)
    args = parser.parse_args(argv)
    failed = False
    for project in args.project or (ROOT, ROOT / "compat", ROOT / "adapters"):
        project = project.resolve()
        expected = manifest_text(project)
        target = project / "MANIFEST.in"
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != expected:
                print("stale generated manifest: " + str(target), file=sys.stderr)
                failed = True
        else:
            target.write_text(expected, encoding="utf-8")
    return int(failed)


if __name__ == "__main__":
    raise SystemExit(main())
